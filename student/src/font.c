static const uint8_t font_block[FONT_HEIGHT] = {
	0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
	0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF
};

const uint8_t *font_get_char(char c)
{
	if (c >= 0x20 && c <= 0x5A) {
		return font_data[c - 0x20];
	}
	/* Lowercase — map to uppercase */
	if (c >= 'a' && c <= 'z') {
		return font_data[c - 'a' + ('A' - 0x20)];
	}
	return font_block;
}
