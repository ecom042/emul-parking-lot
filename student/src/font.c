const uint8_t *font_glyph(char c)
{
	if (c == ' ') {
		return glyphs[0];
	}
	if (c >= 'A' && c <= 'Z') {
		return glyphs[1 + (c - 'A')];
	}
	if (c >= '0' && c <= '9') {
		return glyphs[27 + (c - '0')];
	}
	if (c == '.') {
		return glyphs[37];
	}
	if (c == '-') {
		return glyphs[38];
	}
	return NULL;
}
