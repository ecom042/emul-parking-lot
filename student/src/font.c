static const uint8_t dot[FONT_H] = {0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C};
static const uint8_t blank[FONT_H];

const uint8_t *font_glyph(char c)
{
	if (c >= '0' && c <= '9') {
		return digits[c - '0'];
	}
	if (c >= 'A' && c <= 'Z') {
		return letters[c - 'A'];
	}
	if (c == '.') {
		return dot;
	}
	return blank;
}
