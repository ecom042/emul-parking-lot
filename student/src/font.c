const uint8_t *font_glyph(char c)
{
	int index = 0; /* caractere desconhecido vira espaço */

	if (c == '.') {
		index = 1;
	} else if (c >= '0' && c <= '9') {
		index = 2 + (c - '0');
	} else if (c >= 'A' && c <= 'Z') {
		index = 12 + (c - 'A');
	}
	return glyphs[index];
}
