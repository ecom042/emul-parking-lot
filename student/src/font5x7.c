/* O espaço é o primeiro da tabela: serve de "glifo em branco" para caracteres desconhecidos. */
#define BLANK_INDEX 0U

static const struct font_glyph *find(char c)
{
	for (size_t i = 0U; i < sizeof(glyphs) / sizeof(glyphs[0]); ++i) {
		if (glyphs[i].character == c) {
			return &glyphs[i];
		}
	}
	return NULL;
}

bool font_has_glyph(char c)
{
	return find(c) != NULL;
}

const struct font_glyph *font_lookup(char c)
{
	const struct font_glyph *glyph = find(c);

	return glyph != NULL ? glyph : &glyphs[BLANK_INDEX];
}

bool font_pixel(const struct font_glyph *glyph, unsigned int col, unsigned int row)
{
	if (col >= FONT_COLS || row >= FONT_ROWS) {
		return false;
	}
	return glyph->rows[row][col] == '#';
}
